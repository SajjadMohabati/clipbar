"""Clipboard handling, sensitive data detection, image storage, and OCR matching Clipboard.swift."""

from __future__ import annotations
import hashlib
import io
import os
import re
import shutil
import subprocess
import time
from pathlib import Path
from typing import List, Optional, Set, Tuple

from clipbar.settings import get_data_dir


def get_images_dir() -> Path:
    img_dir = get_data_dir() / "images"
    img_dir.mkdir(parents=True, exist_ok=True)
    return img_dir


class Clipboard:
    """Reading from, writing to, and pasting with system clipboard on Linux (X11 & Wayland)."""

    # Types apps use to say "don't record this"
    TRANSIENT_TYPES: Set[str] = {
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "x-kde-passwordManagerHint",
        "application/x-nspasteboard-transient-type",
        "application/x-vnd.passwordmanager",
    }

    CONCEALED_TYPES: Set[str] = {
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "application/x-nspasteboard-concealed-type",
    }

    SECRET_PREFIXES: Tuple[str, ...] = (
        "sk-", "sk_live_", "rk_live_", "ghp_", "gho_", "ghs_", "github_pat_",
        "glpat-", "xoxb-", "xoxp-", "AKIA", "AIza",
    )

    @classmethod
    def should_ignore(cls, mime_types: List[str], skip_concealed: bool) -> bool:
        if not mime_types:
            return True
        for m in mime_types:
            if m in cls.TRANSIENT_TYPES:
                return True
            if skip_concealed and m in cls.CONCEALED_TYPES:
                return True
        return False

    @classmethod
    def looks_sensitive(cls, text: str) -> bool:
        trimmed = text.strip()
        if trimmed.startswith("-----BEGIN") and "PRIVATE KEY" in trimmed:
            return True
        if cls.is_card_number(trimmed):
            return True
        if 20 <= len(trimmed.encode("utf-8")) <= 300 and not any(c.isspace() for c in trimmed):
            if any(trimmed.startswith(prefix) for prefix in cls.SECRET_PREFIXES):
                return True
        return False

    @classmethod
    def is_card_number(cls, text: str) -> bool:
        if len(text.encode("utf-8")) > 23:
            return False
        if not all(c.isdigit() or c in (" ", "-") for c in text):
            return False
        digits = [int(c) for c in text if c.isdigit()]
        if not (13 <= len(digits) <= 19):
            return False
        # Luhn check
        total = 0
        for i, digit in enumerate(reversed(digits)):
            doubled = digit if (i % 2 == 0) else digit * 2
            total += (doubled - 9) if doubled > 9 else doubled
        return total % 10 == 0

    @classmethod
    def is_wayland(cls) -> bool:
        return "wayland" in os.environ.get("XDG_SESSION_TYPE", "").lower() or bool(os.environ.get("WAYLAND_DISPLAY"))

    @classmethod
    def can_paste(cls) -> bool:
        """Checks if a simulated paste tool is available on this system."""
        if cls.is_wayland():
            return (
                shutil.which("wtype") is not None
                or shutil.which("ydotool") is not None
                or shutil.which("dotool") is not None
                or shutil.which("xdotool") is not None
            )
        return shutil.which("xdotool") is not None

    @classmethod
    def press_paste(cls) -> None:
        """Sends synthetic Ctrl+V (or Shift+Insert) to the active window."""
        time.sleep(0.05)  # brief pause for window focus to settle
        if cls.is_wayland():
            # Try wtype first (common on Wayland compositors)
            if shutil.which("wtype"):
                try:
                    subprocess.run(["wtype", "-M", "ctrl", "-k", "v", "-m", "ctrl"], check=False)
                    return
                except Exception:
                    pass
            # Try ydotool
            if shutil.which("ydotool"):
                try:
                    # 29 is KEY_LEFTCTRL, 47 is KEY_V
                    subprocess.run(["ydotool", "key", "29:1", "47:1", "47:0", "29:0"], check=False)
                    return
                except Exception:
                    pass
            # Try dotool
            if shutil.which("dotool"):
                try:
                    p = subprocess.Popen(["dotool"], stdin=subprocess.PIPE)
                    p.communicate(input=b"key ctrl+v\n")
                    return
                except Exception:
                    pass
            # Fallback to xdotool (works under XWayland)
            if shutil.which("xdotool"):
                try:
                    subprocess.run(["xdotool", "key", "--clearmodifiers", "ctrl+v"], check=False)
                    return
                except Exception:
                    pass
        else:
            # X11 session: xdotool is standard
            if shutil.which("xdotool"):
                try:
                    subprocess.run(["xdotool", "key", "--clearmodifiers", "ctrl+v"], check=False)
                    return
                except Exception:
                    pass


from collections import OrderedDict


class BoundedCache(OrderedDict):
    """Dictionary with maximum capacity that evicts oldest items to conserve memory."""
    def __init__(self, maxsize: int = 60):
        super().__init__()
        self.maxsize = maxsize

    def __setitem__(self, key, value):
        if key in self:
            self.move_to_end(key)
        super().__setitem__(key, value)
        if len(self) > self.maxsize:
            self.popitem(last=False)

    def get(self, key, default=None):
        if key in self:
            self.move_to_end(key)
            return self[key]
        return default


class ImageStore:
    """Stores copied images as PNG named after SHA-256 hash. Performs OCR with Tesseract."""

    _thumbnail_cache = BoundedCache(maxsize=60)

    @classmethod
    def url(cls, name: str) -> Path:
        return get_images_dir() / name

    @classmethod
    def store(cls, data: bytes, is_png: bool = True) -> Optional[str]:
        if not data:
            return None
        png_data = data
        if not is_png:
            try:
                from clipbar.qt import QImage, QByteArray, QBuffer
                img = QImage.fromData(data)
                if not img.isNull():
                    ba = QByteArray()
                    buf = QBuffer(ba)
                    buf.open(QBuffer.OpenModeFlag.WriteOnly)
                    img.save(buf, "PNG")
                    png_data = ba.data()
            except Exception:
                pass

        sha = hashlib.sha256(png_data).hexdigest()[:16]
        name = f"{sha}.png"
        path = cls.url(name)
        if not path.exists():
            try:
                temp = path.with_suffix(".tmp")
                with open(temp, "wb") as f:
                    f.write(png_data)
                temp.replace(path)
            except Exception:
                return None
        return name

    @classmethod
    def thumbnail(cls, name: str, size: int = 96):
        """Returns QPixmap thumbnail cached in memory."""
        if name in cls._thumbnail_cache:
            return cls._thumbnail_cache[name]
        try:
            from clipbar.qt import QPixmap, Qt
            path = cls.url(name)
            if not path.exists():
                return None
            pix = QPixmap(str(path))
            if pix.isNull():
                return None
            thumb = pix.scaled(
                size, size,
                Qt.AspectRatioMode.KeepAspectRatio,
                Qt.TransformationMode.SmoothTransformation
            )
            cls._thumbnail_cache[name] = thumb
            return thumb
        except Exception:
            return None

    @classmethod
    def recognize_text(cls, name: str) -> str:
        """Extracts text from image using Tesseract OCR if installed on Linux."""
        path = cls.url(name)
        if not path.exists():
            return ""

        # Try pytesseract first
        try:
            import pytesseract
            from PIL import Image
            img = Image.open(path)
            text = pytesseract.image_to_string(img)
            return text.strip()
        except Exception:
            pass

        # Try system tesseract binary
        if shutil.which("tesseract"):
            try:
                res = subprocess.run(
                    ["tesseract", str(path), "stdout", "--oem", "1", "-l", "eng+fas+ara"],
                    stdout=subprocess.PIPE,
                    stderr=subprocess.DEVNULL,
                    check=False,
                    text=True,
                    encoding="utf-8",
                    errors="ignore"
                )
                if res.returncode == 0 and res.stdout:
                    return res.stdout.strip()
            except Exception:
                # Fallback to default language if multi-lang not installed
                try:
                    res = subprocess.run(
                        ["tesseract", str(path), "stdout"],
                        stdout=subprocess.PIPE,
                        stderr=subprocess.DEVNULL,
                        check=False,
                        text=True,
                        encoding="utf-8",
                        errors="ignore"
                    )
                    if res.returncode == 0 and res.stdout:
                        return res.stdout.strip()
                except Exception:
                    pass
        return ""

    @classmethod
    def delete(cls, names: List[str]) -> None:
        for name in names:
            p = cls.url(name)
            if p.exists():
                try:
                    p.unlink()
                except Exception:
                    pass
            cls._thumbnail_cache.pop(name, None)

    @classmethod
    def purge(cls, keeping: Set[str]) -> None:
        images_dir = get_images_dir()
        for f in images_dir.glob("*.png"):
            if f.name not in keeping:
                try:
                    f.unlink()
                except Exception:
                    pass
                cls._thumbnail_cache.pop(f.name, None)


class Icons:
    """Cached system and application icons."""

    _cache = BoundedCache(maxsize=50)

    @classmethod
    def app_icon(cls, source_name: Optional[str]):
        """Looks up application icon using system theme or default fallback."""
        if not source_name:
            return None
        if source_name in cls._cache:
            return cls._cache[source_name]
        try:
            from clipbar.qt import QIcon
            icon = QIcon.fromTheme(source_name.lower())
            if icon.isNull():
                # Try generic desktop application icon
                icon = QIcon.fromTheme("application-x-executable")
            cls._cache[source_name] = icon
            return icon
        except Exception:
            return None

    @classmethod
    def file_icon(cls, path: str):
        key = f"file:{path}"
        if key in cls._cache:
            return cls._cache[key]
        try:
            from clipbar.qt import QIcon, QtWidgets
            p = Path(path)
            if p.is_dir():
                icon = QIcon.fromTheme("folder")
            else:
                icon = QIcon.fromTheme("text-x-generic")
            cls._cache[key] = icon
            return icon
        except Exception:
            return None
